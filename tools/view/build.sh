#!/bin/sh
# Builds src/Marey.Html/view/marey-view.js, the script a notebook page draws a scene with (step F,
# D157): src/Marey.Html.View compiled by Fable, then bundled by esbuild into one classic script that
# defines the global `MareyView`. The output is committed; CI runs this and fails if it differs.
#
#     tools/view/build.sh
#
# Fable is the repository's tool (.config/dotnet-tools.json) and esbuild is pinned in
# package-lock.json, so two runs over the same sources write the same bytes.
set -eu
root=$(cd "$(dirname "$0")/../.." && pwd)
out="$root/tools/view/out"

cd "$root"
dotnet tool restore >/dev/null
rm -rf "$out"
dotnet fable src/Marey.Html.View -o "$out" --noCache >/dev/null

cd "$root/tools/view"
npm ci --silent --no-audit --no-fund
./node_modules/.bin/esbuild "$out/View.js" \
    --bundle --minify --format=iife --global-name=MareyView --platform=browser \
    --banner:js="// Generated by tools/view/build.sh from src/Marey.Html.View. Do not edit; rebuild." \
    --outfile="$root/src/Marey.Html/view/marey-view.js" --log-level=warning
